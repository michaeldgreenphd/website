#!/usr/bin/env python3
"""
Render the auto-synced data blocks into index.html.

Reads scholar_stats.json, substack_posts.json and orcid_works.json (all
regenerated by the daily GitHub Action) and rewrites the marked regions of
index.html, so the page is correct the moment it loads with no browser-side
fetching. Every field is stripped of markup and HTML-escaped on the way in,
and links are only emitted for http(s) URLs.

Marked regions in index.html (each pair must appear exactly once):

    <!-- data:metrics -->        citation metrics line
    <!-- data:chart -->          citations-per-year table with inline bars
    <!-- data:posts -->          five most recent Substack posts
    <!-- data:pubs -->           publication list (summary + year groups)
    <!-- data:orcid-updated -->  "updated <Month Year>" stamp
    <!-- data:media-tally -->    counts of the hand-curated media list by kind
    <!-- data:cv-tally -->       counts from the CV (cv_counts.json)

The media tally is the one block not drawn from a data file: it counts the
data-kind attribute of each entry in the curated <ul id="media-appearances">
in index.html itself, so tagging a new entry is all it takes to update it.
The CV tally comes from cv_counts.json, which the owner edits by hand from
the CV; a mistake there warns and leaves that block alone.

Deterministic: unchanged data produces no diff, so the workflow's commit
step stays quiet. Exits non-zero with a ::error:: line if a marker is
missing or duplicated or a data file is unusable, leaving index.html as is.

Usage:
    python scripts/render_snapshot.py
"""

import html
import json
import re
import sys
from datetime import datetime
from email.utils import parsedate_to_datetime
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
INDEX_PATH = REPO_ROOT / "index.html"
SCHOLAR_PATH = REPO_ROOT / "scholar_stats.json"
SUBSTACK_PATH = REPO_ROOT / "substack_posts.json"
ORCID_PATH = REPO_ROOT / "orcid_works.json"
# Hand-maintained from the owner's CV (not fetched): update it with each new CV
CV_COUNTS_PATH = REPO_ROOT / "cv_counts.json"

MAX_POSTS = 5
# Kinds a curated media entry can carry (data-kind="..."), in display order,
# with the label used for one and for several
MEDIA_KINDS = {
    "podcast": ("podcast appearance", "podcast appearances"),
    "news": ("news article", "news articles"),
    "blog": ("blog post", "blog posts"),
    "talk": ("talk or panel", "talks & panels"),
}
MEDIA_TOTAL_LABEL = "appearances on record"
# Editorial choice: conference abstracts and posters stay on ORCID, not on
# the page (the intro sentence above the list says so).
OMITTED_TYPES = {"conference-abstract", "conference-poster"}
FALLBACK_SCHOLAR_URL = "https://scholar.google.com/citations?user=ea2W0QgAAAAJ&amp;hl=en"

# Only what an HTML parser would treat as a tag, so text such as
# "aged <65 and >85 years" is not cut down to "aged 85 years"
TAG_RE = re.compile(r"</?[A-Za-z][^<>]*>")
# Bidi controls and Unicode tag characters: invisible on the page, but they
# reorder or hide words in the text that is stored and committed
INVISIBLE_RE = re.compile("[\u202a-\u202e\u2066-\u2069\U000e0000-\U000e007f]")


class RenderError(SystemExit):
    def __init__(self, message):
        super().__init__(f"::error::render_snapshot: {message}")


# --- Text helpers -------------------------------------------------------------


def clean(value):
    """Plain text for HTML: strip any markup, decode entities, escape."""
    text = html.unescape(TAG_RE.sub("", "" if value is None else str(value)))
    text = INVISIBLE_RE.sub("", text)
    return html.escape(" ".join(text.split()), quote=True)


def safe_url(value):
    """An href value, or '' when the URL is not plain http(s)."""
    url = ("" if value is None else str(value)).strip()
    if re.match(r"^https?://", url, re.IGNORECASE):
        return html.escape(url, quote=True)
    return ""


def link(url, text):
    href = safe_url(url)
    if not href:
        return text
    return f'<a href="{href}" target="_blank" rel="noopener noreferrer">{text}</a>'


def month_year_iso(value):
    """'2026-07-27' -> 'July 2026' ('' if unparseable)."""
    try:
        return datetime.strptime(str(value)[:10], "%Y-%m-%d").strftime("%B %Y")
    except (TypeError, ValueError):
        return ""


def month_year_rfc(value):
    """RFC 2822 pubDate -> 'May 2026' ('' if unparseable)."""
    try:
        return parsedate_to_datetime(str(value)).strftime("%B %Y")
    except (TypeError, ValueError, IndexError, OverflowError):
        return ""


def load_json(path):
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError, RecursionError) as err:
        raise RenderError(f"cannot read {path.name}: {err}")
    if not isinstance(data, dict):
        raise RenderError(f"{path.name} is not a JSON object")
    return data


def dicts(value):
    """The object entries of a JSON list; anything else is skipped."""
    return [v for v in value if isinstance(v, dict)] if isinstance(value, list) else []


# --- Block renderers ----------------------------------------------------------
# The homepage's desktop layout (index.html, @media (min-width: 64rem)) styles
# these blocks by class name (.metrics, .spark, table.cite-table, .pub-year,
# .year-label, ul.pubs) and by where index.html places them: p.metrics and
# table.cite-table sit in the research section's .section-body, the posts inside
# ul#recent-posts, the publications inside details.pubs-fold. Keep the wrappers
# and class names below as they are.


def citation_series(stats):
    """[(year, citations)] in year order, and whether the last year is partial.

    The last year counts as partial when it is the year of the stats' own
    'updated' date, so the answer depends only on the data, never the clock.
    """
    series = {}
    for entry in dicts(stats.get("citations_per_year")):
        year, count = entry.get("year"), entry.get("citations")
        try:
            year, count = int(year), int(count)
        except (TypeError, ValueError):
            continue
        if count >= 0:
            series[year] = count
    ordered = sorted(series.items())
    updated = str(stats.get("updated") or "")[:4]
    partial = bool(ordered) and updated.isdigit() and int(updated) == ordered[-1][0]
    return ordered, partial


def sparkline(series, partial):
    """A word-sized line of citations per year, set inside the metrics line."""
    width, height = 72, 17
    peak = max(count for _, count in series) or 1
    step = (width - 4) / (len(series) - 1)
    points = [(2 + i * step, 15 - count / peak * 12) for i, (_, count) in enumerate(series)]
    fmt = lambda pts: " ".join(f"{x:.1f},{y:.2f}" for x, y in pts)
    label = "citations per year: " + "; ".join(f"{year}, {count}" for year, count in series)
    end_x, end_y = points[-1]
    parts = [f'<svg class="spark" role="img" aria-label="{html.escape(label, quote=True)}" '
             f'width="{width}" height="{height}" viewBox="0 0 {width} {height}">']
    if partial:
        if len(points) > 2:
            parts.append(f'<polyline points="{fmt(points[:-1])}"/>')
        parts.append(f'<polyline class="spark-partial" points="{fmt(points[-2:])}"/>')
        parts.append(f'<circle class="spark-end spark-open" cx="{end_x:.1f}" cy="{end_y:.2f}" r="2"/>')
    else:
        parts.append(f'<polyline points="{fmt(points)}"/>')
        parts.append(f'<circle class="spark-end" cx="{end_x:.1f}" cy="{end_y:.2f}" r="2"/>')
    parts.append("</svg>")
    return "".join(parts)


def render_metrics(stats):
    metrics = stats.get("metrics")
    metrics = metrics if isinstance(metrics, dict) else {}
    values = [metrics.get("citations"), metrics.get("h_index"), metrics.get("i10_index")]
    if any(v is None for v in values):
        raise RenderError("scholar_stats.json is missing citations/h_index/i10_index")
    citations, h_index, i10 = (clean(v) for v in values)
    profile = safe_url(stats.get("profile_url")) or FALLBACK_SCHOLAR_URL
    when = month_year_iso(stats.get("updated"))
    tail = f", {when}" if when else ""
    series, partial = citation_series(stats)
    spark = sparkline(series, partial) if len(series) > 1 else " "
    return (
        f'<p class="metrics">{citations} citations{spark}· <span class="nowrap">h-index {h_index}</span> · '
        f'<span class="nowrap">i10-index {i10}</span> — '
        f'<a href="{profile}" target="_blank" rel="noopener noreferrer">Google Scholar</a>{tail}</p>'
    )


def career_stage(year, stages):
    """'PhD year 3' for a year inside a stage, else ''."""
    for stage in stages:
        if stage["from"] <= year and (stage["to"] is None or year <= stage["to"]):
            return stage["label"], f'{stage["label"]} year {year - stage["from"] + 1}'
    return "", ""


def render_chart(stats, stages):
    """Citations per year as a table: year, career stage, a bar and the count.

    Bars share one scale from zero; the partial current year is an unfilled
    bar with a dashed edge, and a darker rule marks a change of career stage.
    """
    series, partial = citation_series(stats)
    if not series:
        return ""
    peak = max(count for _, count in series) or 1
    rows, previous = [], None
    for i, (year, count) in enumerate(series):
        group, stage = career_stage(year, stages)
        row_class = ' class="stage-start"' if previous is not None and group != previous else ""
        previous = group
        bar_class = "cite-bar partial" if partial and i == len(series) - 1 else "cite-bar"
        width = count / peak * 80
        rows.append(
            f'        <tr{row_class}><th scope="row">{year}</th><td class="cite-stage">{clean(stage)}</td>'
            f'<td class="cite-val"><span class="{bar_class}" style="width: {width:.1f}%"></span>'
            f'<span class="cite-n">{count}</span></td></tr>'
        )
    return "\n".join([
        '<table class="cite-table">',
        "    <caption>citations per year</caption>",
        "    <tbody>",
        *rows,
        "    </tbody>",
        "</table>",
    ])


def render_posts(feed):
    posts = [p for p in dicts(feed.get("posts")) if p.get("title")][:MAX_POSTS]
    if not posts:
        raise RenderError("substack_posts.json has no posts")
    items = []
    for post in posts:
        when = month_year_rfc(post.get("pubDate"))
        meta = f' <span class="meta">{when}</span>' if when else ""
        description = clean(post.get("description"))
        body = f'\n    <p class="fine">{description}</p>' if description else ""
        items.append(f"<li>{link(post.get('link'), clean(post.get('title')))}{meta}{body}</li>")
    return "\n".join(items)


def venue_for(work):
    journal = clean(work.get("journal"))
    if journal:
        return journal
    work_type = str(work.get("type") or "").strip().lower()
    if not work_type or work_type == "journal-article":
        return ""
    if work_type == "preprint":
        return "Preprint"
    return clean(work_type.replace("-", " ").capitalize())


def render_pubs(orcid):
    works = [
        w for w in dicts(orcid.get("works"))
        if w.get("title") and str(w.get("type") or "").strip().lower() not in OMITTED_TYPES
    ]
    if not works:
        raise RenderError("orcid_works.json has no publishable works")

    by_year = {}
    for work in works:
        try:
            year = int(str(work.get("year") or "").strip() or 0)
        except ValueError:
            year = 0
        by_year.setdefault(year, []).append(work)

    groups = [f'<summary id="pubs-summary">show all {len(works)} publications</summary>']
    for year in sorted(by_year, reverse=True):  # 0 (undated) naturally sorts last
        label = str(year) if year else "undated"
        lines = [f'<div class="pub-year">', f'<h3 class="year-label">{label}</h3>', '<ul class="pubs">']
        for work in by_year[year]:
            entry = link(work.get("url"), clean(work.get("title")))
            venue = venue_for(work)
            if venue:
                entry += f' — <span class="journal">{venue}</span>'
            lines.append(f"    <li>{entry}</li>")
        lines += ["</ul>", "</div>"]
        groups.append("\n".join(lines))
    return "\n".join(groups)


def tally_marks(count):
    """Tally marks as an inline SVG: groups of four strokes and a slash."""
    step, group_gap, height = 5, 9, 14
    strokes, x = [], 3
    for group_start in range(0, count, 5):
        in_group = min(5, count - group_start)
        for k in range(min(4, in_group)):
            strokes.append(f"M{x + k * step} 2V{height - 2}")
        if in_group == 5:
            strokes.append(f"M{x - 2} {height - 3}L{x + 3 * step + 2} 3")
        x += 3 * step + group_gap
    width = x - group_gap + 3
    return (
        f'<svg class="tally-marks" viewBox="0 0 {width} {height}" width="{width}" height="{height}" '
        f'aria-hidden="true" focusable="false"><path d="{"".join(strokes)}"/></svg>'
    )


def render_tally(aria_label, total, rows):
    """A tally block: a total line, then one row per (count, label) with marks.

    Shared by the media and CV tallies so both read the same: Fraunces
    numerals, Plex Mono labels, tally marks in --ink on the desktop spread.
    """
    lines = [f'<div class="tally" role="group" aria-label="{html.escape(aria_label, quote=True)}">']
    if total is not None:
        n, label = total
        lines.append(f'    <p class="tally-total"><span class="tally-n">{n}</span> '
                     f'<span class="tally-label">{html.escape(label, quote=False)}</span></p>')
    lines.append('    <ul class="tally-rows">')
    for n, label in rows:
        lines.append(f'        <li><span class="tally-n">{n}</span> '
                     f'<span class="tally-label">{html.escape(label, quote=False)}</span>{tally_marks(n)}</li>')
    lines += ["    </ul>", "</div>"]
    return "\n".join(lines)


def render_media_tally(doc):
    """Count the curated media list by data-kind; the list lives in index.html."""
    opener = '<ul class="rows" id="media-appearances">'
    if doc.count(opener) != 1:
        raise RenderError("the curated list ul#media-appearances is missing or duplicated in index.html")
    start = doc.index(opener) + len(opener)
    items = doc[start:doc.index("</ul>", start)]
    counts = {kind: 0 for kind in MEDIA_KINDS}
    for match in re.finditer(r"<li\b([^>]*)>", items):
        kind = re.search(r'\bdata-kind="([^"]*)"', match.group(1))
        if kind and kind.group(1) in counts:
            counts[kind.group(1)] += 1
        else:
            # Counted nowhere rather than failing the whole data refresh
            print(f"::warning::render_snapshot: a media entry has no known data-kind "
                  f"({', '.join(MEDIA_KINDS)}): {match.group(0)}")
    rows = [(counts[k], one if counts[k] == 1 else several)
            for k, (one, several) in MEDIA_KINDS.items() if counts[k]]
    if not rows:
        raise RenderError("the curated media list has no tagged entries")
    return render_tally("Select media appearances by kind",
                        (sum(counts.values()), MEDIA_TOTAL_LABEL), rows)


def cv_count(entry, where):
    """(count, label) from one cv_counts.json entry; ValueError if malformed."""
    if not isinstance(entry, dict):
        raise ValueError(f"{where} is not an object")
    count, label = entry.get("count"), entry.get("label")
    if isinstance(count, bool) or not isinstance(count, int) or count < 0:
        raise ValueError(f"{where} needs a whole-number count")
    if not isinstance(label, str) or not label.strip():
        raise ValueError(f"{where} needs a label")
    return count, " ".join(label.split())


def load_career_stages():
    """Career stages from cv_counts.json for the citations table, or [].

    Each stage is {"label", "from", optional "to"}; a stage without "to" runs
    on, so its year count advances by itself. A mistake warns and drops the
    stage column's labels rather than failing the data refresh.
    """
    try:
        data = json.loads(CV_COUNTS_PATH.read_text(encoding="utf-8"))
        entries = data.get("career_stages", []) if isinstance(data, dict) else None
        if not isinstance(entries, list):
            raise ValueError("career_stages must be a list")
        stages = []
        for i, entry in enumerate(entries):
            if not isinstance(entry, dict):
                raise ValueError(f"career_stages[{i}] is not an object")
            label, start, end = entry.get("label"), entry.get("from"), entry.get("to")
            if not isinstance(label, str) or not label.strip():
                raise ValueError(f"career_stages[{i}] needs a label")
            if isinstance(start, bool) or not isinstance(start, int):
                raise ValueError(f"career_stages[{i}] needs a whole-number 'from' year")
            if end is not None and (isinstance(end, bool) or not isinstance(end, int) or end < start):
                raise ValueError(f"career_stages[{i}] has an unusable 'to' year")
            stages.append({"label": " ".join(label.split()), "from": start, "to": end})
        return stages
    except (OSError, ValueError, RecursionError, AttributeError) as err:
        print(f"::warning::render_snapshot: career_stages in cv_counts.json unusable, stage labels left out: {err}")
        return []


def render_cv_tally():
    """The CV tally from cv_counts.json, or None (with a warning) if unusable.

    The file is hand-edited, so a mistake in it warns and leaves the block
    as it was instead of failing the whole data refresh.
    """
    try:
        data = json.loads(CV_COUNTS_PATH.read_text(encoding="utf-8"))
        if not isinstance(data, dict):
            raise ValueError("the file is not a JSON object")
        total = cv_count(data.get("total"), "total")
        entries = data.get("rows")
        if not isinstance(entries, list) or not entries:
            raise ValueError("rows must be a non-empty list")
        rows = [cv_count(e, f"rows[{i}]") for i, e in enumerate(entries)]
    except (OSError, ValueError, RecursionError) as err:
        print(f"::warning::render_snapshot: cv_counts.json is unusable, CV tally left as is: {err}")
        return None
    return render_tally("Counts from the CV", total, [r for r in rows if r[0]])


# --- Splicing -----------------------------------------------------------------


def splice(doc, name, content, inline=False):
    start, end = f"<!-- data:{name} -->", f"<!-- /data:{name} -->"
    if doc.count(start) != 1 or doc.count(end) != 1:
        raise RenderError(f"marker data:{name} is missing or duplicated in index.html")
    i = doc.index(start) + len(start)
    j = doc.index(end)
    if j < i:
        raise RenderError(f"marker data:{name} is out of order in index.html")
    if inline:
        return doc[:i] + content + doc[j:]
    # Indent generated lines to match the start marker's line
    line_start = doc.rfind("\n", 0, i) + 1
    indent = re.match(r"[ \t]*", doc[line_start:i]).group(0)
    body = "\n".join(indent + line if line else "" for line in content.split("\n"))
    return doc[:i] + "\n" + body + "\n" + indent + doc[j:]


def main():
    original = INDEX_PATH.read_text(encoding="utf-8")
    scholar = load_json(SCHOLAR_PATH)
    substack = load_json(SUBSTACK_PATH)
    orcid = load_json(ORCID_PATH)

    orcid_updated = month_year_iso(orcid.get("updated"))
    if not orcid_updated:
        raise RenderError("orcid_works.json has no usable 'updated' date")

    doc = original
    doc = splice(doc, "metrics", render_metrics(scholar))
    doc = splice(doc, "chart", render_chart(scholar, load_career_stages()))
    doc = splice(doc, "posts", render_posts(substack))
    doc = splice(doc, "pubs", render_pubs(orcid))
    doc = splice(doc, "orcid-updated", orcid_updated, inline=True)
    doc = splice(doc, "media-tally", render_media_tally(doc))
    cv_tally = render_cv_tally()
    if cv_tally is not None:
        doc = splice(doc, "cv-tally", cv_tally)

    if doc == original:
        print("index.html data blocks unchanged.")
        return
    # Encode before opening: write_text() empties the file first, so an
    # encoding error there would leave a blank index.html to be committed.
    INDEX_PATH.write_bytes(doc.encode("utf-8"))
    print("Rendered data blocks into index.html.")


if __name__ == "__main__":
    try:
        main()
    except RenderError as err:
        print(err, file=sys.stderr)
        sys.exit(1)
